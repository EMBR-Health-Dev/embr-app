// Builds every EMBR logo file from one definition, so the wordmark and
// the compact mark can never drift between the website, apps and PDFs.
//
//   node scripts/brand/build-brand-assets.cjs
//
// Needs opentype.js (outlines the font) and Playwright (renders PNGs).
// Neither is a project dependency; if they are missing, run once:
//   npm i --no-save --prefix /tmp/embr-brand opentype.js@1.3.4
//   NODE_PATH=/tmp/embr-brand/node_modules node scripts/brand/build-brand-assets.cjs
//
// Rules for using the output: docs/BRAND-ASSETS.md.
const fs = require("node:fs");
const path = require("node:path");

const ROOT = path.resolve(__dirname, "../..");
const FONT = path.join(ROOT, "apps/web/src/fonts/InstrumentSerif-Regular.ttf");
const OUT = path.join(ROOT, "assets/brand");

// The master definition. Change it here, rebuild, and every surface follows.
const WORD = "EMBR";
const TRACKING = 0.32; // em, between letters
const PLUM = "#2A1F39";
const PEARL = "#FAF7FB";
// Compact mark, on a 100 unit square: a framed E.
const MARK = { frameInset: 6, frameStroke: 1.25, letterHeight: 46 };
// Small sizes need a heavier frame to stay visible.
const ICON = { frameInset: 14, frameStroke: 2, letterHeight: 40 };

function load(name) {
  try {
    return require(name);
  } catch {
    try {
      return require(require.resolve(name, { paths: ["/opt/node22/lib/node_modules"] }));
    } catch {
      console.error(`Missing ${name}. See the header of this file.`);
      process.exit(1);
    }
  }
}
const opentype = load("opentype.js");
const font = opentype.loadSync(FONT);

function outline(text, size, tracking) {
  const glyphs = font.stringToGlyphs(text);
  const p = new opentype.Path();
  let x = 0;
  glyphs.forEach((g, i) => {
    p.extend(g.getPath(x, 0, size));
    x += (g.advanceWidth / font.unitsPerEm) * size + (i < glyphs.length - 1 ? tracking * size : 0);
  });
  const bb = p.getBoundingBox();
  return { d: p.toPathData(2), x: bb.x1, y: bb.y1, w: bb.x2 - bb.x1, h: bb.y2 - bb.y1 };
}
const r = (n) => Number(n.toFixed(2));

function wordmarkSvg(fill) {
  const o = outline(WORD, 100, TRACKING);
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${r(o.x)} ${r(o.y)} ${r(o.w)} ${r(o.h)}" role="img" aria-label="EMBR"><path fill="${fill}" d="${o.d}"/></svg>\n`;
}

function markBody(fill, spec) {
  const e = outline("E", 100, 0);
  const s = spec.letterHeight / e.h;
  const tx = 50 - (e.x + e.w / 2) * s;
  const ty = 50 - (e.y + e.h / 2) * s;
  const i = spec.frameInset;
  return (
    `<rect x="${i}" y="${i}" width="${100 - 2 * i}" height="${100 - 2 * i}" fill="none" stroke="${fill}" stroke-width="${spec.frameStroke}"/>` +
    `<path fill="${fill}" transform="translate(${r(tx)} ${r(ty)}) scale(${r(s * 1000) / 1000})" d="${e.d}"/>`
  );
}
function markSvg(fill, spec = MARK, background) {
  const bg = background ? `<rect width="100" height="100" fill="${background}"/>` : "";
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 100 100" role="img" aria-label="EMBR">${bg}${markBody(fill, spec)}</svg>\n`;
}

const files = {
  "embr-wordmark.svg": wordmarkSvg("currentColor"),
  "embr-wordmark-dark.svg": wordmarkSvg(PLUM),
  "embr-wordmark-light.svg": wordmarkSvg(PEARL),
  "embr-mark.svg": markSvg("currentColor"),
  "embr-mark-dark.svg": markSvg(PLUM),
  "embr-mark-light.svg": markSvg(PEARL),
  "embr-favicon.svg": markSvg(PEARL, ICON, PLUM),
};
fs.mkdirSync(OUT, { recursive: true });
for (const [name, svg] of Object.entries(files)) fs.writeFileSync(path.join(OUT, name), svg);

// Copies that each app serves itself (they cannot read assets/brand at runtime).
const copies = [
  ["embr-favicon.svg", "apps/web/src/app/icon.svg"],
  ["embr-favicon.svg", "apps/admin/src/app/icon.svg"],
  ["embr-wordmark-dark.svg", "docs/content/field-guide/embr-wordmark-dark.svg"],
  ["embr-wordmark-light.svg", "docs/content/field-guide/embr-wordmark-light.svg"],
];
for (const [from, to] of copies) {
  fs.mkdirSync(path.dirname(path.join(ROOT, to)), { recursive: true });
  fs.copyFileSync(path.join(OUT, from), path.join(ROOT, to));
}

// Wordmark path data for code that draws it directly: the web app's
// header and footer, and the BRIEF PDF.
const wm = outline(WORD, 100, TRACKING);
const wordmarkModule =
  `// Generated by scripts/brand/build-brand-assets.cjs. Do not edit by hand.\n` +
  `/** The EMBR wordmark as SVG path data, in a ${r(wm.w)} x ${r(wm.h)} box. */\n` +
  `export const EMBR_WORDMARK = {\n  path: ${JSON.stringify(wm.d)},\n  x: ${r(wm.x)},\n  y: ${r(wm.y)},\n  width: ${r(wm.w)},\n  height: ${r(wm.h)},\n} as const;\n`;
for (const to of [
  "apps/api/src/lib/brand-wordmark.ts",
  "apps/web/src/lib/brand-wordmark.ts",
  "apps/admin/src/lib/brand-wordmark.ts",
]) {
  fs.writeFileSync(path.join(ROOT, to), wordmarkModule);
}

// PNGs for the mobile app, rendered from the same SVGs.
(async () => {
  const { chromium } = load("playwright");
  const browser = await chromium.launch();
  const page = await browser.newPage();
  const png = async (svg, size, out, transparent = false) => {
    await page.setViewportSize({ width: size, height: size });
    await page.setContent(
      `<html><body style="margin:0;background:transparent">${svg.replace("<svg ", `<svg width="${size}" height="${size}" `)}</body></html>`,
    );
    await page.screenshot({ path: path.join(ROOT, out), omitBackground: transparent });
  };
  const m = "apps/mobile/assets/";
  await png(markSvg(PEARL, ICON, PLUM), 1024, m + "icon.png");
  await png(markSvg(PEARL, ICON, PLUM), 48, m + "favicon.png");
  // Android adaptive icon: the system crops to the inner 66%.
  const adaptive = { frameInset: 26, frameStroke: 1.8, letterHeight: 26 };
  await png(markSvg(PEARL, adaptive), 1024, m + "android-icon-foreground.png", true);
  await png(markSvg("#FFFFFF", adaptive), 1024, m + "android-icon-monochrome.png", true);
  await png(
    `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 1 1"><rect width="1" height="1" fill="${PLUM}"/></svg>`,
    1024,
    m + "android-icon-background.png",
  );
  await png(markSvg(PLUM), 512, m + "splash-icon.png", true);
  // Touch icon for the website (phones saving it to the home screen).
  await png(markSvg(PEARL, ICON, PLUM), 180, "assets/brand/embr-touch-icon.png");
  // Link preview image (Open Graph): the pearl wordmark centred on plum.
  {
    const o = outline(WORD, 100, TRACKING);
    const h = 84,
      w = (o.w / o.h) * h;
    const share = `<html><body style="margin:0;width:1200px;height:630px;background:${PLUM};display:flex;align-items:center;justify-content:center">${wordmarkSvg(PEARL).replace("<svg ", `<svg width="${w}" height="${h}" `)}</body></html>`;
    await page.setViewportSize({ width: 1200, height: 630 });
    await page.setContent(share);
    await page.screenshot({ path: path.join(ROOT, "assets/brand/embr-share.png") });
  }
  await browser.close();
  console.log(
    `Wrote ${Object.keys(files).length} SVGs to assets/brand, ${copies.length} copies, brand-wordmark.ts, 6 mobile PNGs, the touch icon and the share image.`,
  );
})();
